"""Lockfile check (design rule D5): does the target fix what its SBOM lists, or is it chosen when the SBOM is made?

A source project declares its dependencies in manifests. Unless a lockfile fixes every version, the dependency
tree is resolved when the SBOM is generated: only generators that run the build tool list the transitive
dependencies, and for npm and pip the versions they list can change from one scan to the next, and with the
environment of the scan. Each dependency manifest under the target gets one status:

  locked       a lockfile fixes every version, or the manifest is one: a requirements file whose requirements
               are all hashed, or that pip-compile or uv wrote
  pinned       every declared version is exact, but the transitive tree is resolved when the SBOM is generated
  unlocked     some declared versions are ranges, branches or missing
  not checked  dependencies computed in code, an unreadable file, or an ecosystem this check does not cover

The survey reads files and runs nothing. It runs before the generators, which run build tools that write into
the target (Gradle leaves a .gradle directory behind). A container image is not surveyed: it is the built
artifact, whose installed packages are what the generators read, which is what D5 asks for when a project is
not locked. Gradle version catalogs are not read; versions declared through them count as exact.
"""

from __future__ import annotations

import ast
import configparser
import json
import os
import re
import tomllib
import xml.etree.ElementTree as ET
from collections.abc import Callable, Iterable, Iterator, Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from packaging.requirements import InvalidRequirement, Requirement

SCHEMA = "chainguard.lockfiles/v1"
STATUSES = ("locked", "pinned", "unlocked", "not checked")
NOT_LOCKED = ("pinned", "unlocked")
# Never searched: hidden directories (version control, tool state, CI configuration), installed packages,
# vendored code and build output. Nothing in them is a manifest the project maintains.
SKIP_DIRS = frozenset(
    {
        "node_modules",
        "bower_components",
        "jspm_packages",
        "vendor",
        "target",
        "build",
        "dist",
        "venv",
        "site-packages",
        "__pycache__",
    }
)
MAX_BYTES = 5_000_000
NPM_LOCKS = ("package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml", "bun.lock", "bun.lockb")
PYTHON_LOCKS = ("poetry.lock", "pdm.lock", "uv.lock", "Pipfile.lock", "pylock.toml")
LOCKFILES = frozenset((*NPM_LOCKS, *PYTHON_LOCKS, "gradle.lockfile", "go.sum", "Cargo.lock", "Gemfile.lock"))
NOT_COVERED = {"go.mod": "go", "Cargo.toml": "cargo", "Gemfile": "rubygems", "composer.json": "composer"}
PURL_TYPES = {"npm": "npm", "pypi": "pypi", "maven": "maven", "gradle": "maven"}  # the components each declares

_SHA = re.compile(r"[0-9a-f]{40}")
_COMMENT = re.compile(r"(^|\s+)#.*$")
_RESOLVER_WROTE = re.compile(r"autogenerated by (?:pip-compile|uv)\b|#\s+via\b", re.IGNORECASE)
_SCHEME = re.compile(r"[A-Za-z][A-Za-z0-9+.\-]*://")
_NPM_EXACT = re.compile(r"=?v?\d+\.\d+\.\d+(?:-[0-9A-Za-z.\-]+)?(?:\+[0-9A-Za-z.\-]+)?")
_POETRY_EXACT = re.compile(r"(?:==?)?\s*\d[\w.+!\-]*")
_PROPERTY = re.compile(r"\$\{([^}]+)\}")
_GRADLE_COMMENTS = re.compile(r"/\*.*?\*/|//[^\n]*", re.DOTALL)
_GRADLE_STRING = re.compile(r"""["']([\w.\-]+):([\w.\-]+):([^"'\s]+)["']""")
_GRADLE_MAP = re.compile(
    r"""\bgroup\s*[:=]\s*["']([^"']+)["']\s*,\s*name\s*[:=]\s*["']([^"']+)["']"""
    r"""(?:\s*,\s*version\s*[:=]\s*["']([^"']*)["'])?"""
)
_GRADLE_BARE = re.compile(
    r"""\b(?:api|implementation|compileOnly|runtimeOnly|testImplementation|testCompileOnly|testRuntimeOnly|"""
    r"""annotationProcessor|kapt|developmentOnly|compile|runtime|testCompile|testRuntime|classpath)"""
    r"""\s*\(?\s*(?:(?:enforcedPlatform|platform)\s*\(\s*)?["']([\w.\-]+):([\w.\-]+)["']"""
)
_RESOLVED_LATER = "; the transitive tree is resolved when the SBOM is generated"


@dataclass
class Manifest:
    path: str  # relative to the target root
    ecosystem: str
    status: str
    lockfile: str | None = None
    declared: int | None = None  # dependencies it declares, local paths left out
    not_exact: list[str] = field(default_factory=list)  # those not pinned to one version, with the reason
    note: str = ""

    def as_dict(self) -> dict[str, Any]:
        return {
            "path": self.path,
            "ecosystem": self.ecosystem,
            "status": self.status,
            "lockfile": self.lockfile,
            "declared": self.declared,
            "not_exact": self.not_exact,
            "note": self.note,
        }


def _rel(path: Path, root: Path) -> str:
    return path.relative_to(root).as_posix()


def _first(here: Path, names: Iterable[str], root: Path) -> str | None:
    """The first of ``names`` that is a file in ``here``, relative to the root."""
    return next((_rel(here / n, root) for n in names if (here / n).is_file()), None)


def _decide(
    rel: str, ecosystem: str, entries: list[tuple[str, str | None]], lock: str | None, no_lock: str, extra: str = ""
) -> Manifest:
    """A manifest's status from its entries (name, why not exact) and the lockfile that covers it, if any."""
    not_exact = [] if lock else [f"{name} ({why})" for name, why in entries if why]
    if lock:
        status, note = "locked", ""
    elif not_exact:
        status, note = "unlocked", no_lock
    else:
        status, note = "pinned", no_lock + _RESOLVED_LATER
    note = "; ".join(x for x in (note, extra) if x)
    return Manifest(rel, ecosystem, status, lockfile=lock, declared=len(entries), not_exact=not_exact, note=note)


# --------------------------------------------------------------------------- Python


def _reference(url: str) -> str | None:
    """Why a direct reference does not name one version, or None if it does; "local" for a path."""
    if url.startswith("file:") or not _SCHEME.match(url):
        return "local"
    scheme, _, rest = url.partition("://")
    if "+" in scheme or scheme.lower() in ("git", "hg", "svn", "bzr"):
        system = scheme.split("+", 1)[0].lower()
        path = rest.split("#", 1)[0].partition("/")[2]
        ref = path.rpartition("@")[2] if "@" in path else ""
        if _SHA.fullmatch(ref):
            return None
        return f"{system} ref {ref}" if ref else f"{system}, no commit"
    return None  # an archive URL names one file


def _pep508(text: str) -> tuple[str, str | None]:
    """(name, why) for one requirement: why is None if it pins one version, and "local" for a local path."""
    text = text.strip()
    try:
        requirement = Requirement(text)
    except InvalidRequirement:
        egg = re.search(r"[#&]egg=([A-Za-z0-9_.\-]+)", text)
        tail = text.split("#", 1)[0].rstrip("/").rpartition("/")[2].partition("@")[0]
        name = egg.group(1) if egg else (re.sub(r"\.git$", "", tail) or text)
        if _SCHEME.match(text) or text.startswith(("file:", ".", "/", "~")):
            return name, _reference(text)
        return name, "unreadable"
    if requirement.url:
        return requirement.name, _reference(requirement.url)
    specs = list(requirement.specifier)
    if len(specs) == 1 and (specs[0].operator == "===" or (specs[0].operator == "==" and "*" not in specs[0].version)):
        return requirement.name, None
    return requirement.name, str(requirement.specifier) or "no version"


def _logical_lines(text: str) -> Iterator[str]:
    """A pip requirements file's lines, with comments removed and continuations joined."""
    pending = ""
    for raw in text.splitlines():
        line = _COMMENT.sub("", raw).rstrip()
        if line.endswith("\\"):
            pending += line[:-1] + " "
            continue
        line, pending = (pending + line).strip(), ""
        if line:
            yield line
    if pending.strip():
        yield pending.strip()


def _option(line: str) -> tuple[str, str]:
    """(option, value) of a pip option line: ``-r a.txt``, ``-ra.txt`` or ``--requirement=a.txt``."""
    first, _, rest = line.partition(" ")
    if first.startswith("--"):
        option, _, inline = first.partition("=")
    else:
        option, inline = first[:2], first[2:]
    return option, (inline or rest).strip()


def _requirements_file(rel: str, text: str, here: Path, root: Path) -> Manifest | None:
    entries: list[tuple[str, str | None, bool]] = []  # name, why it is not exact, hashed
    includes: list[str] = []
    for line in _logical_lines(text):
        if line.startswith("-"):
            option, value = _option(line)
            if option in ("-r", "--requirement", "-c", "--constraint"):
                includes.append(value)
            elif option in ("-e", "--editable"):
                entries.append((*_pep508(value), False))
            continue
        requirement, *options = re.split(r"\s+(?=--)", line)
        entries.append((*_pep508(requirement), any(o.startswith("--hash") for o in options)))
    entries = [e for e in entries if e[1] != "local"]  # the project itself, or code in the target
    included = f"includes {', '.join(includes)}" if includes else ""
    if not entries:
        return Manifest(rel, "pypi", "not checked", declared=0, note=included) if includes else None
    not_exact = [f"{name} ({why})" for name, why, _ in entries if why]
    if not_exact:
        status, why = "unlocked", ""
    elif all(hashed for *_, hashed in entries):
        status, why = "locked", "every requirement pinned with a hash"
    elif _RESOLVER_WROTE.search(text):
        status, why = "locked", "written by a resolver (pip-compile or uv)"
    else:
        status, why = (
            "pinned",
            "every version exact, but nothing shows the file is closed: transitive requirements may be missing",
        )
    note = "; ".join(x for x in (why, included) if x)
    return Manifest(rel, "pypi", status, declared=len(entries), not_exact=not_exact, note=note)


def _python_lock(here: Path, root: Path) -> str | None:
    return _first(here, PYTHON_LOCKS, root) or next((_rel(p, root) for p in sorted(here.glob("pylock.*.toml"))), None)


def _python_project(rel: str, entries: list[tuple[str, str | None]], here: Path, root: Path) -> Manifest | None:
    entries = [(name, why) for name, why in entries if why != "local"]
    if not entries:
        return None
    return _decide(rel, "pypi", entries, _python_lock(here, root), "no lockfile")


def _poetry(spec: Any) -> str | None:
    if isinstance(spec, list):
        return "several constraints"
    if isinstance(spec, dict):
        if "path" in spec:
            return "local"
        if "git" in spec:
            ref = str(spec.get("rev") or spec.get("tag") or spec.get("branch") or "")
            return None if _SHA.fullmatch(ref) else (f"git ref {ref}" if ref else "git, no commit")
        if "url" in spec:
            return None
        spec = spec.get("version", "")
    spec = str(spec).strip()
    return None if _POETRY_EXACT.fullmatch(spec) else (spec or "no version")


def _pyproject(rel: str, text: str, here: Path, root: Path) -> Manifest | None:
    data = tomllib.loads(text)
    project = data.get("project") or {}
    requirements: list[Any] = list(project.get("dependencies") or [])
    for group in (project.get("optional-dependencies") or {}).values():
        requirements += group if isinstance(group, list) else []
    for group in (data.get("dependency-groups") or {}).values():  # PEP 735
        requirements += group if isinstance(group, list) else []
    entries = [_pep508(r) for r in requirements if isinstance(r, str)]
    poetry = (data.get("tool") or {}).get("poetry") or {}
    tables = [poetry.get("dependencies") or {}, poetry.get("dev-dependencies") or {}]
    tables += [g.get("dependencies") or {} for g in (poetry.get("group") or {}).values() if isinstance(g, dict)]
    for table in tables:
        entries += [(name, _poetry(spec)) for name, spec in table.items() if name.lower() != "python"]
    return _python_project(rel, entries, here, root)


def _pipfile_spec(spec: Any) -> str | None:
    if isinstance(spec, dict):
        if "path" in spec or "file" in spec:
            return "local"
        if "git" in spec:
            ref = str(spec.get("ref") or "")
            return None if _SHA.fullmatch(ref) else (f"git ref {ref}" if ref else "git, no commit")
        spec = spec.get("version", "*")
    spec = str(spec).strip()
    return "no version" if spec in ("", "*") else _pep508(f"x{spec}")[1]


def _pipfile(rel: str, text: str, here: Path, root: Path) -> Manifest | None:
    data = tomllib.loads(text)
    entries = [
        (name, _pipfile_spec(spec))
        for table in ("packages", "dev-packages")
        for name, spec in (data.get(table) or {}).items()
    ]
    return _python_project(rel, entries, here, root)


def _setup_cfg(rel: str, text: str, here: Path, root: Path) -> Manifest | None:
    parser = configparser.ConfigParser(interpolation=None)
    parser.read_string(text)
    lines: list[str] = []
    if parser.has_option("options", "install_requires"):
        lines += parser.get("options", "install_requires").splitlines()
    if parser.has_section("options.extras_require"):
        for _, value in parser.items("options.extras_require"):
            lines += value.splitlines()
    entries = [_pep508(line) for line in lines if line.strip() and not line.strip().startswith("#")]
    return _python_project(rel, entries, here, root)


def _setup_py(rel: str, text: str, here: Path, root: Path) -> Manifest | None:
    """Only literal install_requires and extras_require are read; setup.py is parsed, never executed."""
    requirements: list[str] = []
    computed = False
    for node in ast.walk(ast.parse(text)):
        if not isinstance(node, ast.Call):
            continue
        for keyword in node.keywords:
            if keyword.arg not in ("install_requires", "extras_require"):
                continue
            try:
                value = ast.literal_eval(keyword.value)
            except (ValueError, TypeError, SyntaxError, RecursionError):
                computed = True
                continue
            for group in value.values() if isinstance(value, dict) else [value]:
                if isinstance(group, list | tuple):
                    requirements += [r for r in group if isinstance(r, str)]
                elif isinstance(group, str):
                    requirements += group.splitlines()
    if computed:
        return Manifest(rel, "pypi", "not checked", note="dependencies computed in code")
    return _python_project(rel, [_pep508(r) for r in requirements if r.strip()], here, root)


# --------------------------------------------------------------------------- npm


def _npm_spec(spec: str) -> str | None:
    spec = spec.strip()
    if spec.startswith("npm:"):  # an alias: npm:<name>@<version>
        aliased = spec[4:]
        spec = aliased.rpartition("@")[2] if "@" in aliased[1:] else ""
    if spec.startswith(("file:", "link:", "workspace:", "portal:", ".", "/", "~/")):
        return "local"
    if spec.startswith(("http://", "https://")) and "#" not in spec and not spec.endswith(".git"):
        return None  # a tarball URL names one file
    if spec.startswith(("git", "github:", "gitlab:", "bitbucket:", "http")) or re.fullmatch(
        r"[\w.\-]+/[\w.\-]+(?:#.*)?", spec
    ):
        commit = spec.partition("#")[2]
        return None if _SHA.fullmatch(commit) else (f"git ref {commit}" if commit else "git, no commit")
    return None if _NPM_EXACT.fullmatch(spec) else (spec or "no version")


def _declares_workspaces(path: Path) -> bool:
    try:
        data = json.loads(path.read_text(encoding="utf-8", errors="replace"))
    except (OSError, ValueError):
        return False
    return isinstance(data, dict) and bool(data.get("workspaces"))


def _npm_workspace_lock(here: Path, root: Path) -> str | None:
    """A lockfile in an enclosing workspace root: npm, yarn and pnpm workspaces lock every member there."""
    current = here
    while current != root and root in current.parents:
        current = current.parent
        lock = _first(current, NPM_LOCKS, root)
        if lock and ((current / "pnpm-workspace.yaml").is_file() or _declares_workspaces(current / "package.json")):
            return lock
    return None


def _npm(rel: str, text: str, here: Path, root: Path) -> Manifest | None:
    data = json.loads(text)
    if not isinstance(data, dict):
        raise ValueError("not a JSON object")
    declared: dict[str, Any] = {}
    for key in ("dependencies", "devDependencies", "optionalDependencies"):
        if isinstance(data.get(key), dict):
            declared.update(data[key])
    entries = [(name, _npm_spec(str(spec))) for name, spec in declared.items()]
    entries = [(name, why) for name, why in entries if why != "local"]
    if not entries:
        return None
    lock = _first(here, NPM_LOCKS, root) or _npm_workspace_lock(here, root)
    return _decide(rel, "npm", entries, lock, "no lockfile")


# --------------------------------------------------------------------------- Maven and Gradle


def _expand(value: str, properties: Mapping[str, str], builtin: Mapping[str, str | None]) -> str:
    for _ in range(5):  # properties may refer to properties
        expanded = _PROPERTY.sub(lambda m: properties.get(m.group(1)) or builtin.get(m.group(1)) or m.group(0), value)
        if expanded == value:
            break
        value = expanded
    return value


def _maven_version(version: str) -> str | None:
    if version[:1] in ("[", "(") or version[-1:] in ("]", ")") or "," in version:
        return f"range {version}"
    if version.upper().endswith("-SNAPSHOT"):
        return f"snapshot {version}"
    if version in ("LATEST", "RELEASE"):
        return f"meta-version {version}"
    return None


def _maven(rel: str, text: str, here: Path, root: Path) -> Manifest | None:
    if "<!DOCTYPE" in text:
        return Manifest(rel, "maven", "not checked", note="declares a DTD, which a POM never needs")
    try:
        project = ET.fromstring(text)
    except ET.ParseError as exc:
        return Manifest(rel, "maven", "not checked", note=f"unreadable XML ({exc})")

    def tag(element: ET.Element) -> str:
        return element.tag.rpartition("}")[2] if isinstance(element.tag, str) else ""

    def child(element: ET.Element | None, name: str) -> ET.Element | None:
        return next((c for c in element if tag(c) == name), None) if element is not None else None

    def text_of(element: ET.Element | None, name: str) -> str | None:
        found = child(element, name)
        return found.text.strip() if found is not None and found.text and found.text.strip() else None

    block = child(project, "properties")
    properties = {tag(p): (p.text or "").strip() for p in block} if block is not None else {}
    parent = child(project, "parent")
    builtin = {
        "project.version": text_of(project, "version") or text_of(parent, "version"),
        "project.parent.version": text_of(parent, "version"),
    }
    blocks = [child(project, "dependencies")]
    profiles = child(project, "profiles")
    if profiles is not None:
        blocks += [child(p, "dependencies") for p in profiles if tag(p) == "profile"]
    dependencies = [d for b in blocks if b is not None for d in b if tag(d) == "dependency"]
    if not dependencies:
        return None
    entries: list[tuple[str, str | None]] = []
    inherited = 0
    for dependency in dependencies:
        coordinate = f"{text_of(dependency, 'groupId')}:{text_of(dependency, 'artifactId')}"
        raw = text_of(dependency, "version")
        if raw is None or raw == "${project.version}":
            entries.append((coordinate, None))  # managed by dependencyManagement, a parent or a BOM; or a module
            continue
        version = _expand(raw, properties, builtin)
        if "${" in version:
            inherited += 1  # a property a parent defines: this file alone cannot say
            entries.append((coordinate, None))
            continue
        entries.append((coordinate, _maven_version(version)))
    extra = f"{inherited} version{'s' if inherited != 1 else ''} from a parent's properties" if inherited else ""
    # lockfile.json is the maven-lockfile plugin's; Maven itself has no lockfile format.
    return _decide(rel, "maven", entries, _first(here, ("lockfile.json",), root), "Maven has no lockfile format", extra)


def _gradle_dynamic(version: str) -> bool:
    return (
        "+" in version
        or version.startswith("latest.")
        or version[:1] in ("[", "(")
        or version[-1:] in ("]", ")")
        or version.endswith("-SNAPSHOT")
    )


def _gradle(rel: str, text: str, here: Path, root: Path) -> Manifest | None:
    code = _GRADLE_COMMENTS.sub("", text)
    declared: list[tuple[str, str | None]] = [
        (f"{m.group(1)}:{m.group(2)}", m.group(3).split(":", 1)[0].split("@", 1)[0])
        for m in _GRADLE_STRING.finditer(code)
    ]
    declared += [(f"{m.group(1)}:{m.group(2)}", m.group(3) or None) for m in _GRADLE_MAP.finditer(code)]
    declared += [(f"{m.group(1)}:{m.group(2)}", None) for m in _GRADLE_BARE.finditer(code)]
    if not declared:
        return None
    # A version in a variable is not knowable from this file, and counts as exact.
    entries = [
        (coordinate, version if version and "$" not in version and _gradle_dynamic(version) else None)
        for coordinate, version in declared
    ]
    entries = [(c, f"dynamic {why}" if why else None) for c, why in entries]
    lock = _first(here, ("gradle.lockfile",), root)
    if lock is None and (here / "gradle" / "dependency-locks").is_dir():
        lock = _rel(here / "gradle" / "dependency-locks", root)
    unversioned = sum(1 for _, version in declared if not version)
    extra = f"{unversioned} without a version, managed by a platform or plugin" if unversioned else ""
    return _decide(rel, "gradle", entries, lock, "no gradle.lockfile", extra)


# --------------------------------------------------------------------------- the survey

Parser = Callable[[str, str, Path, Path], Manifest | None]
PARSERS: dict[str, tuple[str, Parser]] = {
    "package.json": ("npm", _npm),
    "pyproject.toml": ("pypi", _pyproject),
    "Pipfile": ("pypi", _pipfile),
    "setup.cfg": ("pypi", _setup_cfg),
    "setup.py": ("pypi", _setup_py),
    "pom.xml": ("maven", _maven),
    "build.gradle": ("gradle", _gradle),
    "build.gradle.kts": ("gradle", _gradle),
}


def _parser(path: Path) -> tuple[str, Parser] | None:
    if path.name in PARSERS:
        return PARSERS[path.name]
    if path.suffix == ".txt" and ("requirements" in path.name.lower() or path.parent.name.lower() == "requirements"):
        return "pypi", _requirements_file  # the files Syft and cdxgen read as pip requirements
    return None


def _files(root: Path) -> Iterator[Path]:
    for current, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith(".") and d not in SKIP_DIRS)
        for filename in sorted(filenames):
            yield Path(current) / filename


def survey(root: Path) -> dict[str, Any]:
    """Every dependency manifest under ``root`` with its status, and every lockfile. Reads files, runs nothing."""
    root = Path(root).resolve()
    manifests: list[Manifest] = []
    lockfiles: list[str] = []
    for path in _files(root):
        if path.is_symlink():
            continue  # never read through a link out of the target
        rel = _rel(path, root)
        if path.name in LOCKFILES or (path.name.startswith("pylock.") and path.suffix == ".toml"):
            lockfiles.append(rel)
        if path.name in NOT_COVERED:
            manifests.append(Manifest(rel, NOT_COVERED[path.name], "not checked", note="ecosystem not covered"))
            continue
        chosen = _parser(path)
        if chosen is None:
            continue
        ecosystem, parse = chosen
        try:
            if path.stat().st_size > MAX_BYTES:
                found = Manifest(rel, ecosystem, "not checked", note="larger than 5 MB")
            else:
                found = parse(rel, path.read_text(encoding="utf-8", errors="replace"), path.parent, root)
        except (OSError, ValueError, TypeError, SyntaxError, RecursionError, configparser.Error) as exc:
            found = Manifest(rel, ecosystem, "not checked", note=f"unreadable ({type(exc).__name__})")
        if found is not None:
            manifests.append(found)
    return {
        "schema": SCHEMA,
        "status": "checked",
        "skipped": "hidden directories, " + ", ".join(sorted(SKIP_DIRS)),
        "manifests": [m.as_dict() for m in manifests],
        "lockfiles": lockfiles,
    }


def not_applicable() -> dict[str, Any]:
    """The survey of a target that is not a source directory."""
    return {"schema": SCHEMA, "status": "not applicable: a built artifact, whose installed packages are read"}


def summarize(found: Mapping[str, Any] | None, inventory: Mapping[str, Any]) -> dict[str, Any]:
    """The summary's lockfile section: the survey's manifests, and for each ecosystem they declare, how many
    components of it each generator lists, and lists alone."""
    if found is None:
        return {"status": "not checked: this run predates the lockfile check"}
    if found.get("status") != "checked":
        return {"status": found.get("status") or "not checked"}
    manifests = list(found.get("manifests") or [])
    generators = sorted({g for entry in inventory.values() for g in entry.found_by})
    components = {}
    for purl_type in sorted({PURL_TYPES[m["ecosystem"]] for m in manifests if m["ecosystem"] in PURL_TYPES}):
        entries = [e for e in inventory.values() if e.type == purl_type]
        components[purl_type] = {
            "components": len(entries),
            "by_generator": {g: sum(1 for e in entries if g in e.found_by) for g in generators},
            "by_one_generator": {g: sum(1 for e in entries if e.found_by == {g}) for g in generators},
        }
    return {
        "status": "checked",
        "manifests": manifests,
        "by_status": {s: sum(1 for m in manifests if m["status"] == s) for s in STATUSES},
        "lockfiles": list(found.get("lockfiles") or []),
        "components": components,
    }


def warnings(section: Mapping[str, Any]) -> list[str]:
    """One warning naming every manifest that is not locked, or none."""
    flagged = [m for m in section.get("manifests") or [] if m["status"] in NOT_LOCKED]
    if not flagged:
        return []
    shown = "; ".join(f"{m['path']} ({m['status']})" for m in flagged[:5])
    more = f"; and {len(flagged) - 5} more" if len(flagged) > 5 else ""
    plural, them = ("s", "them") if len(flagged) != 1 else ("", "it")
    return [
        f"{len(flagged)} dependency manifest{plural} not locked (D5): {shown}{more}. What the SBOM lists from {them} "
        f"is resolved when it is generated: lock {them}, or scan the built artifact"
    ]
