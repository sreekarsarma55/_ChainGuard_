"""Check the lockfile check (CI runs this; no network, no tools).

A synthetic source tree with every shape the rules of design rule D5 distinguish, and the status each must get:

  npm       a lockfile beside it, or at a workspace root; exact versions without one; ranges, git and tags; local
            paths ignored; package.json files under node_modules, build output and hidden directories never read
  pip       pinned; closed by pip-compile or uv; every requirement hashed, or only some; loose (a range, a bare
            name, a git branch, a wildcard); a git commit; local paths; includes; requirements/ directories;
            requirements.in and vendored files never read
  Python    pyproject.toml ([project], Poetry, tool settings only), Pipfile, setup.cfg, and setup.py read
            literally, never run
  Maven     exact, managed, the project's own modules, ranges through properties, snapshots, meta-versions, a
            parent's properties, the maven-lockfile plugin, malformed XML, DTDs, aggregators
  Gradle    static, dynamic, map notation, Kotlin, a lockfile, comments, files without dependencies
  others    go.mod: not checked, never passed silently
  run       the survey runs before any generator (which may write a lockfile into the target), is stored in the
            manifest, reported, warned about once even when reprocessed, not applicable to images, and not
            checked for runs made before it existed

    python3 tests/checks/check_lockfiles.py
"""

