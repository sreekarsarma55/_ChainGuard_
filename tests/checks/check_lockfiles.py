def write_tree(root: Path, tree: dict[str, object]) -> None:
    for rel, content in tree.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content if isinstance(content, str) else json.dumps(content), encoding="utf-8")


def check_rules(failures: list[str]) -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        write_tree(root, TREE)
        found = lockfiles.survey(root)
    by_path = {m["path"]: m for m in found["manifests"]}
    for extra in sorted(set(by_path) - set(EXPECTED)):
        failures.append(f"{extra}: listed ({by_path[extra]['status']}), but must not be read")
    for path, (status, fields) in EXPECTED.items():
        got = by_path.get(path)
        if got is None:
            failures.append(f"{path}: not listed, expected {status}")
            continue
        if got["status"] != status:
            failures.append(f"{path}: {got['status']}, expected {status} ({got})")
        for key, want in fields.items():
            if key == "note":
                if want not in got["note"]:
                    failures.append(f"{path}: note {got['note']!r} lacks {want!r}")
            elif got.get(key) != want:
                failures.append(f"{path}: {key} {got.get(key)!r}, expected {want!r}")
    for path, fragment in NOTES.items():
        if path in by_path and fragment not in by_path[path]["note"]:
            failures.append(f"{path}: note {by_path[path]['note']!r} lacks {fragment!r}")
    if set(found["lockfiles"]) != LOCKFILES:
        failures.append(f"lockfiles {sorted(found['lockfiles'])}, expected {sorted(LOCKFILES)}")
    return found


def entry(key: str, *generators: str) -> correlate.InventoryEntry:
    ptype, rest = key.split("/", 1)
    name, version = rest.rsplit("@", 1)
    return correlate.InventoryEntry(key, ptype, "", name.rsplit("/", 1)[-1], version, found_by=set(generators))


def check_summary(failures: list[str], found: dict) -> None:
    inventory = {
        e.key: e
        for e in (
            entry("maven/g/a@1", "cdxgen"),
            entry("maven/g/b@1", "cdxgen", "syft"),
            entry("pypi/x@1", "syft", "cdxgen"),
            entry("npm/y@1", "syft"),
            entry("deb/debian/z@1", "syft"),
        )
    }
    section = lockfiles.summarize(found, inventory)
    want_status = {s: sum(1 for _, (st, _) in EXPECTED.items() if st == s) for s in lockfiles.STATUSES}
    if section.get("by_status") != want_status:
        failures.append(f"summary by_status {section.get('by_status')}, expected {want_status}")
    want_components = {
        "maven": {
            "components": 2,
            "by_generator": {"cdxgen": 2, "syft": 1},
            "by_one_generator": {"cdxgen": 1, "syft": 0},
        },
        "npm": {
            "components": 1,
            "by_generator": {"cdxgen": 0, "syft": 1},
            "by_one_generator": {"cdxgen": 0, "syft": 1},
        },
        "pypi": {
            "components": 1,
            "by_generator": {"cdxgen": 1, "syft": 1},
            "by_one_generator": {"cdxgen": 0, "syft": 0},
        },
    }
    if section.get("components") != want_components:
        failures.append(f"summary components {section.get('components')}, expected {want_components}")
    flagged = want_status["pinned"] + want_status["unlocked"]
    warned = lockfiles.warnings(section)
    if len(warned) != 1 or not warned[0].startswith(f"{flagged} dependency manifests not locked (D5):"):
        failures.append(f"warnings {warned}, expected one naming {flagged} manifests")
    if lockfiles.warnings(
        lockfiles.summarize({**found, "manifests": [m for m in found["manifests"] if m["status"] == "locked"]}, {})
    ):
        failures.append("locked manifests raised a warning")
    for survey, want in (
        (None, "not checked: this run predates the lockfile check"),
        (lockfiles.not_applicable(), "not applicable: a built artifact, whose installed packages are read"),
    ):
        got = lockfiles.summarize(survey, inventory)
        if got != {"status": want} or lockfiles.warnings(got):
            failures.append(f"summary of {survey}: {got}, expected only the status {want!r}")
    text = "\n".join(report.lockfile_lines(section))
    for needle in (
        "## Dependency manifests (design rule D5)",
        "| `npm-loose/package.json` | npm | **unlocked** |",
        "b (1.x \\|\\| 2.x)",  # a pipe inside a cell must not break the table
        "| `npm-locked/package.json` | npm | locked | npm-locked/package-lock.json | 1 |",
        "maven 2 (cdxgen alone 1)",
    ):
        if needle not in text:
            failures.append(f"summary.md section lacks {needle!r}")
    console = report.render_console(
        {
            "components": {"per_generator": {}, "union": 0},
            "vulnerabilities": {"per_pipeline": {}, "union": 0, "reported_by_one_pipeline": 0},
            "failed_steps": [],
            "lockfiles": section,
        }
    )
    if (
        f"Dependency manifests (D5): {want_status['locked']} locked" not in console
        or "not locked: cfg/setup.cfg" not in console
    ):
        failures.append(f"console line missing or wrong: {console!r}")


