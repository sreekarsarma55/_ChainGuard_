def pom(deps: list[tuple[str, str, str | None]], properties: dict[str, str] | None = None, version: str = "1.0") -> str:
    props = "".join(f"<{k}>{v}</{k}>" for k, v in (properties or {}).items())
    body = "".join(
        f"<dependency><groupId>{g}</groupId><artifactId>{a}</artifactId>"
        + (f"<version>{v}</version>" if v is not None else "")
        + "</dependency>"
        for g, a, v in deps
    )
    return (
        '<project xmlns="http://maven.apache.org/POM/4.0.0"><modelVersion>4.0.0</modelVersion>'
        f"<groupId>t</groupId><artifactId>t</artifactId><version>{version}</version>"
        f"<properties>{props}</properties><dependencies>{body}</dependencies></project>"
    )


