def run_dir(root: Path, kind: str, survey: dict | None) -> Path:
    run = root / f"run-{kind}"
    (run / "raw").mkdir(parents=True)
    (run / "raw" / "syft.cdx.json").write_text(json.dumps(SBOM))
    (run / "raw" / "syft.trivy.json").write_text(json.dumps({"Results": []}))
    steps = [
        Step("syft", "generate", ["syft"], log="raw/syft.log", output="raw/syft.cdx.json", returncode=0).as_dict(),
        Step("syft+trivy", "scan", ["trivy"], log="raw/t.log", output="raw/syft.trivy.json", returncode=0).as_dict(),
    ]
    manifest = {
        "chainguard": "0.1.0",
        "run_id": run.name,
        "target": {"kind": kind, "spec": "x"},
        "options": {"sbom_format": "cyclonedx"},
        "toolchain": {},
        "warnings": ["a warning the scan raised"],
        "steps": steps,
    }
    if survey is not None:
        manifest["dependency_manifests"] = survey
    (run / "manifest.json").write_text(json.dumps(manifest))
    return run


def check_run_directory(failures: list[str]) -> None:
    survey = {
        "schema": lockfiles.SCHEMA,
        "status": "checked",
        "manifests": [
            lockfiles.Manifest(
                "package.json", "npm", "unlocked", None, 1, ["left-pad (^1.3.0)"], "no lockfile"
            ).as_dict()
        ],
        "lockfiles": [],
    }
    options = pipeline.AnalysisOptions(aliases="scanner")  # no network
    with tempfile.TemporaryDirectory() as tmp:
        cases = {
            "checked": run_dir(Path(tmp), "directory", survey),
            "not checked: this run predates the lockfile check": run_dir(Path(tmp), "dir-old", None),
            "not applicable: a built artifact, whose installed packages are read": run_dir(
                Path(tmp), "image-archive", None
            ),
        }
        # An older directory run has kind "directory"; the second case stands for one.
        old = json.loads((cases["not checked: this run predates the lockfile check"] / "manifest.json").read_text())
        old["target"]["kind"] = "directory"
        (cases["not checked: this run predates the lockfile check"] / "manifest.json").write_text(json.dumps(old))
        for want, run in cases.items():
            pipeline.reprocess(run, options)
            second = pipeline.reprocess(run, options)
            got = json.loads((run / "summary.json").read_text())["lockfiles"]
            if got["status"] != want:
                failures.append(f"run directory: lockfile status {got['status']!r}, expected {want!r}")
            d5 = [w for w in json.loads((run / "manifest.json").read_text())["analysis"]["warnings"] if "(D5)" in w]
            if len(d5) != (want == "checked"):
                failures.append(f"run directory ({want}): D5 warnings in the analysis {d5}")
            if sum("(D5)" in w for w in second.warnings) != (want == "checked"):
                failures.append(
                    f"run directory ({want}): reprocessing repeats or loses the D5 warning: {second.warnings}"
                )
            text = (run / "summary.md").read_text()
            if want == "checked" and "## Dependency manifests (design rule D5)" not in text:
                failures.append("run directory: summary.md has no dependency-manifests section")
            if want != "checked" and f"**Dependency manifests (D5):** {want}." not in text:
                failures.append(f"run directory: summary.md does not say {want!r}")


def check_scan(failures: list[str]) -> None:
    """scan() must survey the target before any generator runs: here the generator writes a lockfile into it."""
    with tempfile.TemporaryDirectory() as tmp:
        target = Path(tmp) / "project"
        target.mkdir()
        (target / "package.json").write_text(json.dumps({"dependencies": {"left-pad": "^1.3.0"}}))

        def fake_run(step: Step, run: Path, *, timeout: int = 1800) -> Step:
            output = run / (step.output or "")
            output.parent.mkdir(parents=True, exist_ok=True)
            if step.kind == "generate":
                output.write_text(json.dumps(SBOM))
                (target / "package-lock.json").write_text("{}")  # what a generator running npm install does
            else:
                output.write_text(json.dumps({"Results": []}))
            step.returncode = 0
            return step

        saved = (pipeline.check_toolchain, toolchain.environment, runner.run)
        pipeline.check_toolchain = lambda options, needs_docker: ({}, [])
        toolchain.environment = dict
        runner.run = fake_run
        try:
            result = pipeline.scan(
                str(target),
                Path(tmp) / "out",
                pipeline.ScanOptions(generators=("syft",), scanners=("trivy",)),
                analysis=pipeline.AnalysisOptions(aliases="scanner"),
            )
        finally:
            pipeline.check_toolchain, toolchain.environment, runner.run = saved
        manifest = json.loads((result.run_dir / "manifest.json").read_text())
        statuses = {m["path"]: m["status"] for m in (manifest.get("dependency_manifests") or {}).get("manifests") or []}
        if statuses != {"package.json": "unlocked"}:
            failures.append(f"scan: survey {statuses}; it must be taken before the generators write into the target")
        if sum("(D5)" in w for w in result.warnings) != 1:
            failures.append(f"scan: warnings {result.warnings}, expected one D5 warning")
        section = json.loads((result.run_dir / "summary.json").read_text())["lockfiles"]
        if section.get("components", {}).get("npm", {}).get("components") != 1:
            failures.append(f"scan: summary lockfile components {section.get('components')}")


def main() -> None:
    failures: list[str] = []
    found = check_rules(failures)
    check_summary(failures, found)
    check_run_directory(failures)
    check_scan(failures)
    for failure in failures:
        print(f"FAIL  {failure}")
    print(
        f"lockfile check: {len(EXPECTED)} manifest shapes, summary, report, run directory, survey before generators: ",
        end="",
    )
    print("ok" if not failures else f"{len(failures)} failures")
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
